function pickVoice(lang){
  const voices=speechSynthesis.getVoices();
  if(lang==="ta"){
    return voices.find(v=>/^ta(-|_)/i.test(v.lang)) || null;
  }
  return voices.find(v=>/^en-IN/i.test(v.lang))
      || voices.find(v=>/^en(-|_)/i.test(v.lang))
      || null;
}

function splitForNaturalSpeech(text){
  // Keep full stops, question marks and exclamation marks, then create
  // short chunks at commas so the browser has time to pause naturally.
  const sentences=text.match(/[^.!?。！？]+[.!?。！？]+|[^.!?。！？]+$/g) || [text];
  const chunks=[];
  sentences.forEach(sentence=>{
    const parts=sentence.trim().split(/,\s*/);
    parts.forEach((part,index)=>{
      const cleaned=part.trim();
      if(!cleaned) return;
      const punctuation = index < parts.length-1 ? "," : "";
      chunks.push(cleaned + punctuation);
    });
  });
  return chunks;
}

function speakGuide(text,lang,onFinished){
  stopSpeech();
  if(!("speechSynthesis" in window)){
    setVoiceStatus("இந்த browser voice support செய்யவில்லை.");
    return;
  }

  const voice=pickVoice(lang);
  if(lang==="ta" && !voice){
    setVoiceStatus("Tamil voice கிடைக்கவில்லை. macOS Settings → Accessibility → Spoken Content → System Voice-ல் Tamil voice சேர்த்து மீண்டும் முயற்சிக்கவும்.");
    return;
  }

  const chunks=splitForNaturalSpeech(text);
  let index=0;

  const speakNext=()=>{
    if(index>=chunks.length){
      setVoiceStatus("Guide finished.");
      if(onFinished) onFinished();
      return;
    }

    const u=new SpeechSynthesisUtterance(chunks[index]);
    u.lang=lang==="ta" ? "ta-IN" : "en-IN";
    if(voice) u.voice=voice;
    u.rate=lang==="ta" ? 0.80 : 0.90;
    u.pitch=1;
    u.volume=1;

    if(index===0){
      setVoiceStatus(lang==="ta" ? "தமிழ் வழிகாட்டி பேசுகிறது…" : "English guide is speaking…");
    }

    u.onend=()=>{
      index++;
      // Real pause between chunks. This makes commas and sentence breaks
      // much clearer than putting the entire paragraph into one utterance.
      setTimeout(speakNext, 220);
    };

    u.onerror=()=>{
      setVoiceStatus("Voice playback stopped.");
      if(onFinished) onFinished();
    };

    speechSynthesis.speak(u);
  };

  speakNext();
}

function speakBoth(d){
  stopSpeech();
  speakGuide(d.en,"en",()=>{
    setTimeout(()=>{
      speakGuide(d.ta,"ta");
    },500);
  });
}

function stopSpeech(){
  if("speechSynthesis" in window) speechSynthesis.cancel();
  setVoiceStatus("Voice stopped.");
}

